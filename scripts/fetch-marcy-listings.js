#!/usr/bin/env node
/* ============================================================
   fetch-marcy-listings.js — populate marcy/listings.js with REAL
   for-sale listings in Magnolia, Seattle (98199).

   WHY a build-time script (not a live fetch in the browser):
   leadsure.com is a static GitHub Pages site. A browser fetch to a
   listings API would be blocked by CORS (and the API key would be
   exposed on the page). So we fetch here, at build time, and commit
   the result — exactly like the stock-price refresh. The API key
   stays on your machine (env var), never in the repo or the site.

   USAGE:
     RENTCAST_API_KEY=your_key node scripts/fetch-marcy-listings.js
     git add marcy/listings.js && git commit -m "Refresh Marcy listings" && git push

   Get a free key at https://rentcast.io (free tier ~50 req/mo).
   Other providers (NWMLS/IDX, Bridge, RapidAPI) work too — swap the
   `fetchListings` body to match their response shape.

   NOTE on photos: RentCast does not return MLS photos (they are
   license-restricted). `photo` is left null unless the feed provides
   one; the card then shows the placeholder. For real photos you need
   an IDX/VOW feed, or use Google Street View Static (needs a Google key).
   ============================================================ */
const fs = require('fs');
const https = require('https');
const path = require('path');

const KEY = process.env.RENTCAST_API_KEY;
const OUT = path.join(__dirname, '..', 'marcy', 'listings.js');
const ZIP = process.env.MARCY_ZIP || '98199';
const LIMIT = process.env.MARCY_LIMIT || '24';

if (!KEY) {
  console.error('Missing RENTCAST_API_KEY. Usage: RENTCAST_API_KEY=xxx node scripts/fetch-marcy-listings.js');
  process.exit(1);
}

function get(url) {
  return new Promise(function (resolve, reject) {
    const req = https.get(url, { headers: { 'X-Api-Key': KEY, 'Accept': 'application/json' } }, function (res) {
      let body = '';
      res.on('data', function (c) { body += c; });
      res.on('end', function () {
        if (res.statusCode < 200 || res.statusCode >= 300) return reject(new Error('HTTP ' + res.statusCode + ': ' + body.slice(0, 300)));
        try { resolve(JSON.parse(body)); } catch (e) { reject(e); }
      });
    });
    req.on('error', reject);
    req.setTimeout(20000, function () { req.destroy(); reject(new Error('timeout')); });
  });
}

function mapType(t) {
  if (!t) return 'House';
  t = String(t).toLowerCase();
  if (t.indexOf('condo') >= 0) return 'Condo';
  if (t.indexOf('town') >= 0) return 'Townhome';
  return 'House';
}

function toListing(r, i) {
  const price = r.price || r.listPrice || 0;
  const days = r.daysOnMarket != null ? r.daysOnMarket : 99;
  return {
    id: r.id || ('mag-' + String(i + 1).padStart(3, '0')),
    address: r.addressLine1 || r.formattedAddress || 'Address unavailable',
    zip: r.zipCode || ZIP,
    price: Math.round(price),
    beds: r.bedrooms || 0,
    baths: r.bathrooms || 0,
    sqft: r.squareFootage || 0,
    type: mapType(r.propertyType),
    status: days <= 7 ? 'New' : 'Active',
    blurb: [mapType(r.propertyType), r.yearBuilt ? ('built ' + r.yearBuilt) : '', (r.city || 'Magnolia')].filter(Boolean).join(' · '),
    photo: (r.photos && r.photos[0]) || null
  };
}

async function fetchListings() {
  const url = 'https://api.rentcast.io/v1/listings/sale?zipCode=' + ZIP + '&status=Active&limit=' + LIMIT;
  const data = await get(url);
  const arr = Array.isArray(data) ? data : (data.listings || []);
  return arr.map(toListing).filter(function (l) { return l.price > 0 && l.address !== 'Address unavailable'; });
}

(async function () {
  try {
    const listings = await fetchListings();
    if (!listings.length) { console.error('No listings returned — leaving marcy/listings.js unchanged.'); process.exit(1); }
    const header = '/* AUTO-GENERATED by scripts/fetch-marcy-listings.js on ' + new Date().toISOString() + '\n' +
      '   Real for-sale listings (zip ' + ZIP + '). Re-run the script to refresh. */\n';
    const out = header + 'const MARCY_LISTINGS = ' + JSON.stringify(listings, null, 2) + ';\n';
    fs.writeFileSync(OUT, out);
    console.log('Wrote ' + listings.length + ' listings to ' + OUT);
  } catch (e) {
    console.error('Fetch failed:', e.message);
    process.exit(1);
  }
})();
